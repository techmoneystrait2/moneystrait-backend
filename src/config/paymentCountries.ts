export interface PaymentCountry {
  code: string;
  name: string;
  region: string;
  currency: string;
}

export const PAYMENT_COUNTRIES: PaymentCountry[] = Object.entries(REGIONS)
  .flatMap(([region, list]) =>
    list.split(' ').map((entry) => {
      const [code = '', currency = ''] = entry.split(':');
      return { code, name: countryName(code), region, currency };
    }),
  )
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

export const PAYMENT_COUNTRY_CODES = PAYMENT_COUNTRIES.map((country) => country.code);

export const CATALOGUE_SOURCE_CODES = COUNTRY_CODES;
